# Writes src/video/segment_model.jai, the op list of MediaPipe's selfie segmenter for the camera background
# kernels (src/video/segment.jai), from the vendored model. The weights stay in the .tflite, which the
# binary embeds: each op names the byte offsets of its float16 weights and biases there. Activations that
# follow an op are folded into it.
#   pip install tflite numpy; python3 tools/segmenter_convert.py
import os, sys
import numpy as np, tflite
from tflite.BuiltinOperator import BuiltinOperator as BO

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL = 'vendor/selfie_segmenter/selfie_segmenter_landscape.tflite'
buf = open(os.path.join(ROOT, MODEL), 'rb').read()
m = tflite.Model.GetRootAsModel(buf, 0)
g = m.Subgraphs(0)

def shape(t): return [int(x) for x in g.Tensors(t).ShapeAsNumpy()]

def f16_offset(t):  # byte offset of a constant float16 tensor's data in the file
    tt = g.Tensors(t)
    assert tt.Type() == 1, 'float16 weights'
    b = m.Buffers(tt.Buffer())
    pos = b._tab.Vector(b._tab.Offset(4))
    assert pos % 2 == 0 and b.DataLength() == 2 * int(np.prod(shape(t)))
    return pos

dequant = {}  # output tensor -> float16 source tensor
ops = []
users = {}
for i in range(g.OperatorsLength()):
    op = g.Operators(i)
    for j in range(op.InputsLength()): users[op.Inputs(j)] = users.get(op.Inputs(j), 0) + 1
for i in range(g.OperatorsLength()):
    op = g.Operators(i)
    code = m.OperatorCodes(op.OpcodeIndex())
    bc = max(code.BuiltinCode(), code.DeprecatedBuiltinCode())
    ins = [op.Inputs(j) for j in range(op.InputsLength())]
    out = op.Outputs(0)
    o = op.BuiltinOptions()
    if bc == BO.DEQUANTIZE:
        dequant[out] = ins[0]
        continue
    if bc in (BO.CONV_2D, BO.DEPTHWISE_CONV_2D):
        dw = bc == BO.DEPTHWISE_CONV_2D
        x = tflite.DepthwiseConv2DOptions() if dw else tflite.Conv2DOptions()
        x.Init(o.Bytes, o.Pos)
        assert x.FusedActivationFunction() == 0 and x.StrideW() == x.StrideH() and x.DilationWFactor() == 1
        assert not dw or x.DepthMultiplier() == 1
        w = shape(ins[1])
        assert w[1] == w[2]
        ops.append(dict(kind='DW' if dw else 'CONV', a=ins[0], b=-1, out=out, k=w[1], stride=x.StrideW(),
                        valid=x.Padding() == 1, w=f16_offset(dequant[ins[1]]), bias=f16_offset(dequant[ins[2]])))
    elif bc == 32 and code.CustomCode() == b'Convolution2DTransposeBias':
        # MediaPipe's transposed convolution: options are padding, stride w, stride h (int32s).
        opt = np.frombuffer(bytes(op.CustomOptionsAsNumpy()), np.int32)
        w = shape(ins[1])
        assert list(opt[:3]) == [1, 2, 2] and w[0] == 1 and w[1] == 2 and w[2] == 2
        ops.append(dict(kind='TCONV', a=ins[0], b=-1, out=out, k=2, stride=2, valid=True,
                        w=f16_offset(dequant[ins[1]]), bias=f16_offset(dequant[ins[2]])))
    elif bc == BO.MEAN:
        assert shape(out)[1:3] == [1, 1]
        ops.append(dict(kind='MEAN', a=ins[0], b=-1, out=out))
    elif bc in (BO.MUL, BO.ADD):
        a, b = ins
        if shape(a)[1:3] == [1, 1] and shape(b)[1:3] != [1, 1]: a, b = b, a  # b is the one broadcast
        ops.append(dict(kind='MUL' if bc == BO.MUL else 'ADD', a=a, b=b, out=out))
    elif bc == BO.RESIZE_BILINEAR:
        x = tflite.ResizeBilinearOptions()
        x.Init(o.Bytes, o.Pos)
        assert x.HalfPixelCenters() and not x.AlignCorners()
        assert shape(out)[1] == 2 * shape(ins[0])[1] and shape(out)[2] == 2 * shape(ins[0])[2]
        ops.append(dict(kind='UP2', a=ins[0], b=-1, out=out))
    elif bc in (BO.RELU, BO.HARD_SWISH, BO.LOGISTIC):
        prev = [p for p in ops if p['out'] == ins[0]]
        assert len(prev) == 1 and users[ins[0]] == 1 and 'act' not in prev[0]
        prev[0]['act'] = {BO.RELU: 'RELU', BO.HARD_SWISH: 'HSWISH', BO.LOGISTIC: 'SIGMOID'}[bc]
        prev[0]['out'] = out
    else:
        sys.exit(f'unsupported op {bc}')

# Tensors renumbered in the order they're made: 0 is the input, the last the output.
inp, outp = g.Inputs(0), g.Outputs(0)
ids = {inp: 0}
for p in ops: ids[p['out']] = len(ids)
assert ids[outp] == len(ids) - 1
dims = [None] * len(ids)
for t, i in ids.items():
    s = shape(t)
    assert len(s) == 4 and s[0] == 1
    dims[i] = s[1:]

lines = [
    '// Generated by tools/segmenter_convert.py from vendor/selfie_segmenter; don\'t edit.',
    '',
    '// Each tensor\'s height, width and channels (HWC floats): 0 is the RGB input, the last the person mask.',
    'SEG_TENSORS :: [3]s32.[',
]
lines += [f'\t.[{h}, {w}, {c}],' for h, w, c in dims]
lines += [
    '];',
    '',
    '// kind, activation, inputs a and b (-1: none), output, kernel, stride, VALID padding (else SAME), and the',
    '// byte offsets of the float16 weights and biases in SEG_MODEL.',
    'SEG_OPS :: Seg_Op.[',
]
for p in ops:
    b = ids[p['b']] if p['b'] >= 0 else -1
    lines.append(f"\t.{{.{p['kind']}, .{p.get('act', 'NONE')}, {ids[p['a']]}, {b}, {ids[p['out']]}, {p.get('k', 0)}, "
                 f"{p.get('stride', 0)}, {str(p.get('valid', False)).lower()}, {p.get('w', 0)}, {p.get('bias', 0)}}},")
lines += ['];', '']
open(os.path.join(ROOT, 'src/video/segment_model.jai'), 'w', newline='\n').write('\n'.join(lines))
print(f'{len(ops)} ops, {len(dims)} tensors')
